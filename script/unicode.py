#!/usr/bin/env python3
"""Writes src/unicode.h: the character classes the scanner needs.

    python3 script/unicode.py > src/unicode.h

Typst's lexer asks Rust's `char::is_alphanumeric`, `char::is_numeric` and
`unicode_ident`'s XID_Start and XID_Continue. A scanner that guessed these with
a few ranges took the Arabic comma for a letter, so `_البداية_،` lost its
emphasis. The tables come from the Unicode database of the Python that runs
this, which is close enough to Rust's: the classes change at the edges of new
scripts, not in text people write.
"""
import sys
import unicodedata

ALNUM = {"Lu", "Ll", "Lt", "Lm", "Lo", "Nd", "Nl", "No", "Mn", "Mc"}
NUMERIC = {"Nd", "Nl", "No"}


def ranges(pred):
    out, start = [], None
    for cp in range(0x80, 0x110000):
        hit = pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


TABLES = {
    "alnum": lambda c: unicodedata.category(c) in ALNUM,
    "numeric": lambda c: unicodedata.category(c) in NUMERIC,
    "xid_start": lambda c: c.isidentifier(),
    "xid_continue": lambda c: ("a" + c).isidentifier(),
}

w = sys.stdout.write
w("// Generated by script/unicode.py from Unicode %s. Do not edit.\n" % unicodedata.unidata_version)
w("//\n// Ranges of code points from U+0080 up; ASCII is decided in scanner.c.\n\n")
w("#ifndef TREE_SITTER_TYPST_UNICODE_H_\n#define TREE_SITTER_TYPST_UNICODE_H_\n\n#include <stdbool.h>\n#include <stdint.h>\n\n")
w("typedef struct { uint32_t lo, hi; } TypstRange;\n\n")
for name, pred in TABLES.items():
    rs = ranges(pred)
    w("static const TypstRange typst_%s[%d] = {\n" % (name, len(rs)))
    for i in range(0, len(rs), 4):
        w("  " + " ".join("{0x%X, 0x%X}," % r for r in rs[i:i + 4]) + "\n")
    w("};\n\n")
w("""static bool typst_in(const TypstRange *table, uint32_t size, int32_t c) {
  uint32_t lo = 0, hi = size;
  while (lo < hi) {
    uint32_t mid = (lo + hi) / 2;
    if ((uint32_t)c < table[mid].lo) {
      hi = mid;
    } else if ((uint32_t)c > table[mid].hi) {
      lo = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}

#define TYPST_IN(table, c) typst_in(table, sizeof(table) / sizeof(table[0]), c)

#endif  // TREE_SITTER_TYPST_UNICODE_H_
""")
